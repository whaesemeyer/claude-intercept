'use strict';

/**
 * Formats captured HTTP traffic for Claude analysis.
 * Modes: 'api-docs' | 'auth' | 'summary' | 'full'
 */
function buildClaudeExport(captures, mode = 'summary') {
  switch (mode) {
    case 'api-docs': return buildApiDocs(captures);
    case 'auth':     return buildAuthExport(captures);
    case 'summary':  return buildSummary(captures);
    case 'full':     return buildFull(captures);
    default:         return buildSummary(captures);
  }
}

// ── API Documentation mode ────────────────────────────────────────────────────
function buildApiDocsData(captures) {
  const endpoints = [];
  for (const [host, methods] of groupByEndpoint(captures)) {
    for (const [key, samples] of methods) {
      const [method, path] = key.split(' ', 2);
      const sample = samples[0];
      endpoints.push({
        host,
        method,
        path,
        callsCaptured: samples.length,
        statusCodes: [...new Set(samples.map(s => s.responseStatus))],
        contentType: safeContentType(sample.contentType),
        averageDurationMs: Math.round(samples.reduce((a, s) => a + (s.duration || 0), 0) / samples.length),
        requestHeaderNames: getNotableHeaders(sample.requestHeaders || {}).map(([name]) => name),
        requestBodyStructure: sample.requestBody ? bodyStructure(sample.requestBody) : null,
        responseBodyStructure: sample.responseBody ? bodyStructure(sample.responseBody) : null,
      });
    }
  }
  return endpoints;
}

const COMMON_CONTENT_TYPES = new Set([
  'application/json', 'application/xml', 'application/octet-stream',
  'application/x-www-form-urlencoded', 'multipart/form-data',
  'text/plain', 'text/html', 'text/css', 'text/javascript',
  'image/png', 'image/jpeg', 'image/gif', 'image/svg+xml',
]);

function safeContentType(raw) {
  const type = String(raw || '').split(';', 1)[0].trim().toLowerCase();
  return type ? (COMMON_CONTENT_TYPES.has(type) ? type : '[other]') : '';
}

function buildApiDocs(captures) {
  const endpoints = buildApiDocsData(captures);
  const lines = [
    '# API Traffic Analysis',
    `> Captured ${captures.length} requests across ${new Set(captures.map(c => c.host)).size} hosts`,
    '',
  ];

  let previousHost;
  for (const endpoint of endpoints) {
    if (endpoint.host !== previousHost) {
      lines.push(`## Host: ${endpoint.host}`, '');
      previousHost = endpoint.host;
    }
    lines.push(`### ${endpoint.method} ${endpoint.path}`, '');
    lines.push(`- **Calls captured:** ${endpoint.callsCaptured}`);
    lines.push(`- **Status codes:** ${endpoint.statusCodes.join(', ')}`);
    lines.push(`- **Content-Type:** ${endpoint.contentType || '(none)'}`);
    lines.push(`- **Avg duration:** ${endpoint.averageDurationMs}ms`);

    // Documentation exports omit captured header and body values. Credential
    // extraction and full detail remain separate explicit modes.
    if (endpoint.requestHeaderNames.length) {
      lines.push('', '**Request Headers (notable):**');
      endpoint.requestHeaderNames.forEach(name => lines.push(`- \`${name}: [value omitted]\``));
    }
    for (const [label, structure] of [
      ['Request', endpoint.requestBodyStructure],
      ['Response', endpoint.responseBodyStructure],
    ]) {
      if (structure === null) continue;
      lines.push('', `**${label} Body (structure):**`, '```');
      lines.push(typeof structure === 'string' && structure === '[non-JSON body omitted]'
        ? structure : JSON.stringify(structure, null, 2));
      lines.push('```');
    }
    lines.push('');
  }

  lines.push('---');
  lines.push(`*Generated by Claude Intercept — ${new Date().toISOString()}*`);

  return lines.join('\n');
}

// ── Auth Extraction mode ─────────────────────────────────────────────────────
function buildAuthExport(captures) {
  const lines = [
    '# Auth & Credentials Extraction',
    `> Scanned ${captures.length} captures`,
    '',
    '## Authorization Headers',
    '',
  ];

  const authMap = new Map(); // token → { host, scheme, first_seen }
  const cookieMap = new Map(); // host → Set of cookie strings
  const apiKeyHeaders = ['x-api-key', 'x-auth-token', 'x-access-token', 'x-session-token',
                          'api-key', 'apikey', 'x-client-id', 'x-app-key'];

  for (const c of captures) {
    const h = c.requestHeaders || {};
    const host = c.host;

    // Authorization header
    const auth = h['authorization'] || h['Authorization'] || '';
    if (auth) {
      const [scheme, token] = auth.split(' ', 2);
      const key = `${scheme}::${token?.slice(-12)}`;
      if (!authMap.has(key)) {
        authMap.set(key, { host, scheme, token: token || '', url: c.url });
      }
    }

    // API key headers
    for (const hName of apiKeyHeaders) {
      const val = h[hName] || h[hName.toLowerCase()] || '';
      if (val) {
        const key = `${hName}::${val.slice(-8)}`;
        if (!authMap.has(key)) {
          authMap.set(key, { host, scheme: hName, token: val, url: c.url });
        }
      }
    }

    // Cookies
    const cookie = h['cookie'] || h['Cookie'] || '';
    if (cookie) {
      if (!cookieMap.has(host)) cookieMap.set(host, new Set());
      cookieMap.get(host).add(cookie);
    }

    // Bearer in request body / query string
    const urlObj = tryParseUrl(c.url);
    if (urlObj) {
      for (const [k, v] of urlObj.searchParams.entries()) {
        if (/token|access_token|api_key|bearer/i.test(k)) {
          const key = `query::${k}::${v.slice(-8)}`;
          if (!authMap.has(key)) {
            authMap.set(key, { host, scheme: `query param: ${k}`, token: v, url: c.url });
          }
        }
      }
    }
  }

  if (authMap.size === 0) {
    lines.push('*No Authorization headers found.*', '');
  } else {
    for (const [, info] of authMap) {
      lines.push(`### ${info.scheme}`);
      lines.push(`- **Host:** \`${info.host}\``);
      lines.push(`- **From:** \`${info.url}\``);
      lines.push(`- **Value:** \`${info.token}\``);
      lines.push('');
    }
  }

  lines.push('## Cookies', '');
  if (cookieMap.size === 0) {
    lines.push('*No cookies found.*', '');
  } else {
    for (const [host, cookies] of cookieMap) {
      lines.push(`### ${host}`);
      for (const cookie of cookies) {
        const pairs = cookie.split(';').map(s => s.trim()).filter(Boolean);
        pairs.forEach(p => lines.push(`- \`${truncate(p, 200)}\``));
      }
      lines.push('');
    }
  }

  // JSON body token extraction
  lines.push('## Tokens in Request/Response Bodies', '');
  const bodyTokens = [];
  const tokenKeys = /token|access_token|refresh_token|id_token|session_id|sessionToken|auth/i;
  for (const c of captures) {
    for (const body of [c.requestBody, c.responseBody]) {
      if (!body) continue;
      try {
        const parsed = JSON.parse(body);
        findKeys(parsed, tokenKeys, c.host, c.url, bodyTokens);
      } catch {}
    }
  }
  if (!bodyTokens.length) {
    lines.push('*No tokens found in JSON bodies.*', '');
  } else {
    for (const bt of bodyTokens.slice(0, 30)) {
      lines.push(`- **\`${bt.key}\`** on \`${bt.host}\`: \`${truncate(bt.value, 120)}\``);
    }
    lines.push('');
  }

  lines.push('---');
  lines.push(`*Generated by Claude Intercept — ${new Date().toISOString()}*`);
  return lines.join('\n');
}

// ── Summary mode ──────────────────────────────────────────────────────────────
function buildSummary(captures) {
  const summary = summarizeCaptures(captures);

  const lines = [
    '# Traffic Summary',
    '',
    `**Total requests:** ${captures.length}`,
    `**Unique hosts:** ${summary.requestsByHost.length}`,
    `**Avg response time:** ${summary.averageDurationMs}ms`,
    '',
    '## Requests by Host',
    '',
    ...summary.requestsByHost.map(({ host, count }) => `- \`${host}\` — ${count} requests`),
    '',
    '## HTTP Methods',
    '',
    ...summary.methods.map(({ method, count }) => `- **${method}:** ${count}`),
    '',
    '## Status Codes',
    '',
    ...summary.statusClasses.map(({ statusClass, count }) => `- **${statusClass}xx:** ${count}`),
    '',
    '---',
    `*Generated by Claude Intercept — ${new Date().toISOString()}*`,
  ];

  return lines.join('\n');
}

function summarizeCaptures(captures) {
  const hosts = new Map();
  const methods = new Map();
  const statuses = new Map();
  let totalDuration = 0;

  for (const c of captures) {
    hosts.set(c.host, (hosts.get(c.host) || 0) + 1);
    methods.set(c.method, (methods.get(c.method) || 0) + 1);
    const statusClass = Math.floor((c.responseStatus || 0) / 100);
    statuses.set(statusClass, (statuses.get(statusClass) || 0) + 1);
    totalDuration += c.duration || 0;
  }

  return {
    requestsByHost: [...hosts].sort((a, b) => b[1] - a[1]).map(([host, count]) => ({ host, count })),
    methods: [...methods].map(([method, count]) => ({ method, count })),
    statusClasses: [...statuses].map(([statusClass, count]) => ({ statusClass, count })),
    averageDurationMs: captures.length ? Math.round(totalDuration / captures.length) : 0,
  };
}

// ── Full detail mode ─────────────────────────────────────────────────────────
function buildFull(captures) {
  const lines = [
    '# Full Capture Detail',
    `> ${captures.length} requests`,
    '',
  ];

  for (const c of captures) {
    lines.push(`## [${c.id}] ${c.method} ${c.url}`);
    lines.push(`**Status:** ${c.responseStatus}  **Duration:** ${c.duration}ms  **Time:** ${new Date(c.timestamp).toISOString()}`);
    lines.push('');
    lines.push('### Request Headers');
    for (const [k, v] of Object.entries(c.requestHeaders || {})) {
      lines.push(`- \`${k}: ${truncate(String(v), 200)}\``);
    }
    if (c.requestBody) {
      lines.push('### Request Body');
      lines.push('```');
      lines.push(formatBody(c.requestBody, 1200));
      lines.push('```');
    }
    lines.push('### Response Headers');
    for (const [k, v] of Object.entries(c.responseHeaders || {})) {
      lines.push(`- \`${k}: ${truncate(String(v), 200)}\``);
    }
    if (c.responseBody) {
      lines.push('### Response Body');
      lines.push('```');
      lines.push(formatBody(c.responseBody, 2000));
      lines.push('```');
    }
    lines.push('');
    lines.push('---');
    lines.push('');
  }

  lines.push(`*Generated by Claude Intercept — ${new Date().toISOString()}*`);
  return lines.join('\n');
}

// ── Helpers ───────────────────────────────────────────────────────────────────
function groupByEndpoint(captures) {
  const result = new Map();
  for (const c of captures) {
    const host = c.host;
    if (!result.has(host)) result.set(host, new Map());
    const normalizedPath = normalizePath(c.path || '/');
    const key = `${c.method} ${normalizedPath}`;
    const methods = result.get(host);
    if (!methods.has(key)) methods.set(key, []);
    methods.get(key).push(c);
  }
  return result;
}

function normalizePath(path) {
  // Replace UUIDs, numeric IDs, hex strings with placeholders
  return path
    .replace(/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}/gi, ':uuid')
    .replace(/\/\d+(?=\/|$|\?)/g, '/:id')
    .replace(/[?#].*$/, ''); // strip query string for grouping
}

function getNotableHeaders(headers) {
  const notableKeys = [
    'authorization', 'cookie', 'x-api-key', 'x-auth-token', 'x-access-token',
    'content-type', 'accept', 'origin', 'referer', 'x-requested-with',
    'x-forwarded-for', 'user-agent',
  ];
  return Object.entries(headers).filter(([k]) => notableKeys.includes(k.toLowerCase()));
}

function formatBody(body, maxLen) {
  if (!body) return '';
  let out = body;
  try { out = JSON.stringify(JSON.parse(body), null, 2); } catch {}
  return truncate(out, maxLen);
}

function bodyStructure(body) {
  let value;
  try { value = JSON.parse(body); } catch { return '[non-JSON body omitted]'; }

  function describe(item, depth = 0) {
    if (item === null) return 'null';
    if (depth >= 6) return '[nested structure omitted]';
    if (Array.isArray(item)) return item.length ? [describe(item[0], depth + 1)] : [];
    if (typeof item !== 'object') return typeof item;
    const shape = Object.create(null);
    for (const [key, nested] of Object.entries(item).slice(0, 50)) {
      shape[key] = describe(nested, depth + 1);
    }
    return shape;
  }

  return describe(value);
}

function truncate(str, max) {
  if (!str) return '';
  const s = String(str);
  return s.length > max ? s.slice(0, max) + `… [+${s.length - max} chars]` : s;
}

function tryParseUrl(url) {
  try { return new URL(url); } catch { return null; }
}

function findKeys(obj, pattern, host, url, results, prefix = '') {
  if (typeof obj !== 'object' || obj === null || results.length > 30) return;
  for (const [k, v] of Object.entries(obj)) {
    const fullKey = prefix ? `${prefix}.${k}` : k;
    if (pattern.test(k) && typeof v === 'string' && v.length > 8) {
      results.push({ key: fullKey, value: v, host, url });
    }
    if (typeof v === 'object') findKeys(v, pattern, host, url, results, fullKey);
  }
}

// ── Machine-readable export ───────────────────────────────────────────────────
/**
 * Structured JSON for programmatic/agent consumption. Summary and API
 * documentation omit captured header and body values. Only full mode returns
 * raw capture records.
 * `meta` overrides are shallow-merged last so callers can inject a fixed
 * `generatedAt` for deterministic tests.
 */
function buildJsonExport(captures, meta = {}) {
  const requestedMode = meta.mode || 'summary';
  const mode = ['summary', 'api-docs', 'auth', 'full'].includes(requestedMode)
    ? requestedMode : 'summary';
  const header = {
    count: captures.length,
    hosts: [...new Set(captures.map(c => c.host))].sort(),
    generatedAt: new Date().toISOString(),
    ...meta,
    mode,
  };
  if (mode === 'summary') return { meta: header, summary: summarizeCaptures(captures) };
  if (mode === 'api-docs') return { meta: header, endpoints: buildApiDocsData(captures) };
  if (mode === 'auth') return { meta: header, findings: buildAuthExport(captures) };
  return { meta: header, captures };
}

module.exports = { buildClaudeExport, buildJsonExport };
